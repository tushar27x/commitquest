// The edge colours of the tier backdrops, so a screen wider than the art can continue each scene
// past its left and right edges with flat bands (the road, the ground line, walls, sky) instead of
// a mirrored copy. Used by sync-design.mjs, which writes the result to lib/scene-edges.ts.

import { readFileSync } from "node:fs";
import { inflateSync } from "node:zlib";

/** Decodes an 8-bit RGBA, non-interlaced PNG (the only kind in the design kit) into rows of pixels. */
export function decodePng(file) {
  const png = readFileSync(file);
  const width = png.readUInt32BE(16);
  const height = png.readUInt32BE(20);
  const [depth, colourType, , , interlace] = png.subarray(24, 29);
  if (depth !== 8 || colourType !== 6 || interlace !== 0) {
    throw new Error(`${file}: expected an 8-bit RGBA PNG without interlacing`);
  }
  const idat = [];
  for (let at = 8; at < png.length; ) {
    const length = png.readUInt32BE(at);
    const type = png.toString("latin1", at + 4, at + 8);
    if (type === "IDAT") idat.push(png.subarray(at + 8, at + 8 + length));
    at += 12 + length;
  }
  const raw = inflateSync(Buffer.concat(idat));
  const stride = width * 4;
  const pixels = Buffer.alloc(stride * height);
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)];
    const line = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    const out = pixels.subarray(y * stride, (y + 1) * stride);
    const up = y > 0 ? pixels.subarray((y - 1) * stride, y * stride) : Buffer.alloc(stride);
    for (let i = 0; i < stride; i++) {
      const a = i >= 4 ? out[i - 4] : 0;
      const b = up[i];
      const c = i >= 4 ? up[i - 4] : 0;
      let predictor = 0;
      if (filter === 1) predictor = a;
      else if (filter === 2) predictor = b;
      else if (filter === 3) predictor = (a + b) >> 1;
      else if (filter === 4) {
        const p = a + b - c;
        const pa = Math.abs(p - a);
        const pb = Math.abs(p - b);
        const pc = Math.abs(p - c);
        predictor = pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
      }
      out[i] = (line[i] + predictor) & 0xff;
    }
  }
  return { width, height, pixel: (x, y) => [...pixels.subarray((y * width + x) * 4, (y * width + x) * 4 + 3)] };
}

const STRIP = 12; // columns sampled at each edge
const STEP = 12; // rows per colour stop above the ground
// Every scene ends in the same ground: the road (the bottom 26 art rows of the phone art, 22 of the
// desktop art), then a 2-row dark edge and a 2-row lit line.
const ROAD = { phone: 26, desktop: 22 };
const LINE = 2;

const hex = (rgb) => `#${rgb.map((c) => Math.round(c).toString(16).padStart(2, "0")).join("")}`;

/** The per-channel median of some colours, so a lit window, a star or a mote doesn't tint them. */
function median(colours) {
  return [0, 1, 2].map((i) => {
    const values = colours.map((rgb) => rgb[i]).sort((a, b) => a - b);
    return values[values.length >> 1];
  });
}

/**
 * One edge of a scene, from the bottom up: `ground` as hard bands [colour, rows from the bottom
 * where it ends] (road, edge, lit line), then `above` as soft stops [colour, rows from the bottom]
 * every STEP rows, each the median of a STRIP × STEP block, smoothed with its neighbours so
 * bricks, windows and stars don't turn into stripes.
 */
function edge(image, side, size) {
  const x0 = side === "left" ? 0 : image.width - STRIP;
  const block = (from, to) => {
    const colours = [];
    for (let r = from; r < to; r++) for (let x = x0; x < x0 + STRIP; x++) colours.push(image.pixel(x, image.height - 1 - r));
    return median(colours);
  };
  const road = ROAD[size];
  const ground = [
    [hex(block(0, road)), road],
    [hex(block(road, road + LINE)), road + LINE],
    [hex(block(road + LINE, road + 2 * LINE)), road + 2 * LINE],
  ];
  const start = road + 2 * LINE;
  const raw = [];
  for (let from = start; from < image.height; from += STEP) {
    const to = Math.min(from + STEP, image.height);
    raw.push([block(from, to), Math.round((from + to) / 2)]);
  }
  const above = raw.map(([, row], i) => {
    const near = raw.slice(Math.max(0, i - 1), i + 2).map(([rgb]) => rgb);
    const rgb = [0, 1, 2].map((c) => near.reduce((sum, n) => sum + n[c], 0) / near.length);
    return [hex(rgb), row];
  });
  return { ground, above: [[above[0][0], start], ...above, [above.at(-1)[0], image.height]] };
}

/** lib/scene-edges.ts: the bands of every tier's phone and desktop scene, both sides. */
export function sceneEdgesTs(sceneDir, tiers) {
  const lines = [
    "// Generated by scripts/sync-design.mjs from docs/design/art/scenes. Do not edit.",
    "// Each side of each backdrop from the bottom up, in art rows (multiply by the drawn scale):",
    "// `ground` hard bands [colour, row where it ends], then `above` soft stops [colour, row].",
    "",
    'import type { Tier } from "./api/types";',
    "",
    "export type SceneEdge = { ground: readonly (readonly [string, number])[]; above: readonly (readonly [string, number])[] };",
    "",
    "export const SCENE_EDGES: Record<Tier, Record<\"phone\" | \"desktop\", { left: SceneEdge; right: SceneEdge }>> = {",
  ];
  for (const tier of tiers) {
    lines.push(`  ${tier}: {`);
    for (const size of ["phone", "desktop"]) {
      const image = decodePng(`${sceneDir}/${tier.toLowerCase()}-${size}.png`);
      const side = (s) => {
        const { ground, above } = edge(image, s, size);
        const list = (stops) => JSON.stringify(stops).replaceAll("],[", "], [");
        return `{ ground: ${list(ground)}, above: ${list(above)} }`;
      };
      lines.push(`    ${size}: {`, `      left: ${side("left")},`, `      right: ${side("right")},`, "    },");
    }
    lines.push("  },");
  }
  lines.push("};", "");
  return lines.join("\n");
}
