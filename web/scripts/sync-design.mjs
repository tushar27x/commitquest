// Generates the web app's design files from the design kit in docs/design/:
//   docs/design/tokens.json  -> app/theme.css        (Tailwind 4 @theme)
//   docs/design/art/**       -> public/art/**         (byte copies of the PNG art)
//   docs/design/art/scenes   -> lib/scene-edges.ts    (each backdrop's edge colours, scene-edges.mjs)
// All outputs are committed. Run `npm run design` after the kit changes;
// `npm run design:check` fails if the committed files have drifted.
// If docs/ is missing (web/ deployed on its own), it skips and keeps the committed copies.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { sceneEdgesTs } from "./scene-edges.mjs";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const kit = join(web, "..", "docs", "design");
const check = process.argv.includes("--check");

if (!existsSync(kit)) {
  console.warn(`sync-design: ${kit} not found, keeping the committed design files`);
  process.exit(0);
}

const kebab = (s) =>
  s.replace(/([a-z])([A-Z0-9])/g, "$1-$2").replace(/([0-9])([A-Za-z])/g, "$1-$2").toLowerCase();

function themeCss(tokens) {
  const lines = [
    "/* Generated by scripts/sync-design.mjs from docs/design/tokens.json. Do not edit. */",
    "",
    // `static`: every token is a CSS variable even when no utility uses it, because the app
    // reads class accents as var(--color-class-*) in inline styles (lib/art.ts).
    "@theme static {",
    "  /* Only the Pixel Realm palette: Tailwind's default colours are switched off. */",
    "  --color-*: initial;",
  ];
  for (const [name, hex] of Object.entries(tokens.color)) {
    lines.push(`  --color-${kebab(name)}: ${hex};`);
  }
  lines.push("", "  /* Class accents: name, score bar and selection only. */");
  for (const [name, hex] of Object.entries(tokens.classAccent)) {
    lines.push(`  --color-class-${name.toLowerCase()}: ${hex};`);
  }
  const outline = tokens.color.outline;
  lines.push(
    "",
    "  /* Pixel rules: no radius, hard borders and drop shadows. */",
    "  --radius-*: initial;",
    `  --shadow-px: ${tokens.pixel.border};`,
    `  --shadow-px-drop: ${tokens.pixel.border}, ${tokens.pixel.dropShadow};`,
    `  --shadow-px-parchment: 0 0 0 4px ${outline}, inset 0 0 0 4px ${tokens.color.parchmentBorder};`,
    "}",
    "",
  );
  return lines.join("\n");
}

/** Every file under `dir`, as paths relative to it (sorted, `/`-separated). */
function listFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => relative(dir, join(entry.parentPath, entry.name)).split("\\").join("/"))
    .sort();
}

const tokens = JSON.parse(readFileSync(join(kit, "tokens.json"), "utf8"));
const outputs = [
  [join(web, "app", "theme.css"), themeCss(tokens)],
  [join(web, "lib", "scene-edges.ts"), sceneEdgesTs(join(kit, "art", "scenes"), ["CAMPFIRE", "VILLAGE", "KEEP", "CITADEL"])],
];

// The art: docs/design/art/<path> -> public/art/<path>, and nothing else in public/art.
const artSrc = join(kit, "art");
const artOut = join(web, "public", "art");
for (const file of listFiles(artSrc)) outputs.push([join(artOut, file), readFileSync(join(artSrc, file))]);
const expected = new Set(outputs.map(([path]) => path));
const stale = listFiles(artOut)
  .map((file) => join(artOut, file))
  .filter((path) => !expected.has(path));

const same = (current, content) =>
  typeof content === "string" ? current.toString("utf8") === content : Buffer.compare(current, content) === 0;

let drift = false;
for (const [path, content] of outputs) {
  if (existsSync(path) && same(readFileSync(path), content)) continue;
  if (check) {
    console.error(`sync-design: ${path} is out of date, run \`npm run design\``);
    drift = true;
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`sync-design: wrote ${path}`);
  }
}
for (const path of stale) {
  if (check) {
    console.error(`sync-design: ${path} is not in docs/design/art, run \`npm run design\``);
    drift = true;
  } else {
    rmSync(path);
    console.log(`sync-design: removed ${path}`);
  }
}
process.exit(drift ? 1 : 0);
